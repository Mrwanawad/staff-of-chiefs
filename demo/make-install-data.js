#!/usr/bin/env node
// Builds demo/install-data.js for demo/install.html: the real output of the installer, the status
// check and the uninstaller, run against a throwaway config dir. No model calls, no network.
//
//   node demo/make-install-data.js
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'soc-install-demo-'));
const cfg = path.join(tmp, 'cfg');
fs.mkdirSync(cfg);
// A user who already has a status line, so the demo shows that it is kept.
fs.writeFileSync(path.join(cfg, 'settings.json'), '{\n  "statusLine": { "type": "command", "command": "my-statusline" }\n}\n');

const scrub = s => s.split(cfg).join('~/.claude').replace(/soc-backup-[\dT-]+Z/g, 'soc-backup-<timestamp>');
const node = (file, args = []) => scrub(execFileSync(process.execPath, [file, ...args],
  { env: { ...process.env, CLAUDE_CONFIG_DIR: cfg, SOC_NO_BROWSER: '1' }, encoding: 'utf8' }));

const data = {
  node: process.version,
  dry: node(path.join(ROOT, 'scripts/install.js'), ['--dry-run']),
  real: node(path.join(ROOT, 'scripts/install.js'), ['--statusline']),
  again: node(path.join(ROOT, 'scripts/install.js'), ['--statusline']),
  status: node(path.join(cfg, 'staff-of-chiefs/runtime/config.js'), ['status']),
  uninstall: node(path.join(ROOT, 'scripts/uninstall.js')),
};
fs.rmSync(tmp, { recursive: true, force: true });

fs.writeFileSync(path.join(__dirname, 'install-data.js'),
  '// generated by demo/make-install-data.js (real installer output, throwaway config)\nwindow.INSTALL = ' +
  JSON.stringify(data, null, 1) + ';\n');
console.log('demo/install-data.js written');
